/**
 * Turn the sourced geography into a Laravel seeder.
 *
 * Reads the JSON that `source-geography.mjs` produced and writes a PHP seeder
 * for kalaanba-api. Run deliberately, commit the output, and never let the app
 * call Google at seed time — Zone geography is admin-controlled reference data
 * (Zone engine §2/§5), so a human reviews what lands.
 *
 * Usage: node scripts/build-geography-seeder.mjs <input.json> <output.php>
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(process.argv[2], "utf8"));
const out = process.argv[3];

/**
 * Tamale's localities, which Google does not hold as places. Sourced from
 * PRODUCT.md §11 plus the Zone engine doc's own examples. Google returns the
 * landmarks INSIDE these (a police roundabout, a school, a market) and, when
 * filtered to geographic types, returns nothing at all for 8 of them.
 */
const TAMALE_LOCAL = [
  "Lamashegu",
  "Kalpohin",
  "Vittin",
  "Sakasaka",
  "Choggu",
  "Gumbihini",
  "Aboabo",
  "Bulpela",
  "Taha",
  "Kukuo",
  "Sagnarigu",
  "Nyohini",
  "Tishigu",
];

/**
 * Rows ZoneHierarchySeeder already created. Reused rather than re-created:
 * `city_hubs` is unique on (region_id, code), not on name, so emitting Tamale
 * under a fresh code inserted a SECOND Tamale beside the first and the hub list
 * served two of them. Anything already in the database keeps its id, because
 * other tables reference it.
 */
/**
 * Regions ZoneHierarchySeeder already created. Without this, Northern Region
 * gets a second row under a generated code and the tree grows a duplicate that
 * is invisible until someone reads the table.
 */
const EXISTING_REGIONS = {
  "Northern Region": "8c2f9d0a-2c5b-4e3e-9c1e-6a3b1a0e1002",
};

const EXISTING = {
  Tamale: {
    hubId: "8c2f9d0a-2c5b-4e3e-9c1e-6a3b1a0e1003",
    hubCode: "TML",
    zoneId: "8c2f9d0a-2c5b-4e3e-9c1e-6a3b1a0e1004",
    zoneCode: "tml-central",
    zoneName: "Tamale Central",
  },
};

/** A street or an estate block is not an area someone says they are from. */
const NOT_AN_AREA = /\b(road|street|avenue|highway|lane|close|crescent)\b/i;

const slug = (s) =>
  s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);

const hubs = [];
for (const { hub, areas } of src) {
  const names = [];
  const seen = new Set();
  const add = (name) => {
    const key = name.toLowerCase();
    if (seen.has(key)) return;
    seen.add(key);
    names.push(name);
  };

  if (hub.name === "Tamale") TAMALE_LOCAL.forEach(add);
  for (const area of areas) {
    if (!area.name || NOT_AN_AREA.test(area.name)) continue;
    add(area.name);
  }

  const existing = EXISTING[hub.name];
  hubs.push({
    name: hub.name,
    region: hub.region,
    regionId: EXISTING_REGIONS[hub.region] ?? null,
    code: existing?.hubCode ?? slug(hub.name),
    hubId: existing?.hubId ?? null,
    zoneId: existing?.zoneId ?? null,
    zoneCode: existing?.zoneCode ?? null,
    zoneName: existing?.zoneName ?? null,
    areas: names.sort((a, b) => a.localeCompare(b)),
  });
}

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'");

const rows = hubs
  .map((h) => {
    const areaLines = h.areas.length
      ? "\n                    " +
        h.areas.map((a) => `'${esc(a)}',`).join("\n                    ") +
        "\n                "
      : "";
    const nullable = (v) => (v === null || v === undefined ? "null" : `'${esc(v)}'`);
    return [
      "            [",
      `                'name' => '${esc(h.name)}',`,
      `                'code' => '${esc(h.code)}',`,
      `                'region' => '${esc(h.region)}',`,
      `                'region_id' => ${nullable(h.regionId)},`,
      `                'hub_id' => ${nullable(h.hubId)},`,
      `                'zone_id' => ${nullable(h.zoneId)},`,
      `                'zone_code' => ${nullable(h.zoneCode)},`,
      `                'zone_name' => ${nullable(h.zoneName)},`,
      `                'areas' => [${areaLines}],`,
      "            ],",
    ].join("\n");
  })
  .join("\n");

const php = `<?php

declare(strict_types=1);

namespace Database\\Seeders;

use DateTimeImmutable;
use Illuminate\\Database\\Seeder;
use Illuminate\\Support\\Facades\\DB;

/**
 * Ghana geography for the Zone engine: the regional capitals as City Hubs, and
 * the localities under them as Areas.
 *
 * GENERATED by kalaanba-front/scripts/build-geography-seeder.mjs from data
 * sourced through Google (Geocoding for the cities, Places for the localities)
 * and then reviewed. Regenerate rather than hand-edit, and re-read the diff:
 * this is admin-controlled reference data (Zone engine 2/5) and a name that
 * lands here becomes somewhere a player calls home.
 *
 * WHAT GOOGLE COULD AND COULD NOT DO. Cities resolved perfectly: canonical
 * name, region and centre for all thirteen. Localities did not. Coverage
 * tracks city size, so Accra and Kumasi are well mapped while Tamale, the
 * launch market, is barely mapped at all. Hard-restricted to 25km and filtered
 * to geographic types, 8 of 10 of the names in PRODUCT.md 11 return NOTHING,
 * and unfiltered they return the landmarks inside them: "Lamashegu Police
 * Station Round-about", "Kalpohin SHS", "Aboabo Market". Tamale's list is
 * therefore the product's own, from PRODUCT.md 11 and the Zone doc examples.
 * Four hubs have no Areas at all; the suggestion flow (5) is how they fill.
 *
 * ZONES ARE PROVISIONAL. The Zone doc defines a Zone as a competitive division
 * and an Area as the locality a club represents, while PRODUCT.md 11 lists
 * Tamale's eight localities under the heading "Zones". Which localities group
 * into which division is a football decision an admin makes, not one a seeder
 * should invent, so every Area lands under a single '<City> Central' zone for
 * an admin to remap ("request Area/Zone changes"). Flagged for the Engine
 * Owner.
 *
 * Idempotent: deterministic UUIDv5 ids and insertOrIgnore, so re-running is a
 * no-op and existing rows keep the ids other tables already reference.
 */
class GhanaGeographySeeder extends Seeder
{
    /** Namespace for deterministic ids. Changing it re-keys the whole tree. */
    private const NAMESPACE_UUID = '6ba7b810-9dad-11d1-80b4-00c04fd430c8';

    /** Ghana, as seeded by ZoneHierarchySeeder. Reused so the two agree. */
    private const COUNTRY_ID = '8c2f9d0a-2c5b-4e3e-9c1e-6a3b1a0e1001';

    public function run(): void
    {
        $now = (new DateTimeImmutable('now', timezone_open('UTC')))->format('Y-m-d H:i:s');

        DB::table('countries')->insertOrIgnore([
            'id' => self::COUNTRY_ID,
            'code' => 'GH',
            'name' => 'Ghana',
            'created_at' => $now,
            'updated_at' => $now,
        ]);

        foreach ($this->hubs() as $hub) {
            $regionCode = $this->slug($hub['region']);
            $regionId = $hub['region_id'] ?? $this->uuid5('region:'.$regionCode);

            DB::table('regions')->insertOrIgnore([
                'id' => $regionId,
                'country_id' => self::COUNTRY_ID,
                'code' => $regionCode,
                'name' => $hub['region'],
                'created_at' => $now,
                'updated_at' => $now,
            ]);

            $hubId = $hub['hub_id'] ?? $this->uuid5('hub:'.$hub['code']);
            DB::table('city_hubs')->insertOrIgnore([
                'id' => $hubId,
                'region_id' => $regionId,
                'code' => $hub['code'],
                'name' => $hub['name'],
                'created_at' => $now,
                'updated_at' => $now,
            ]);

            // One provisional division per hub. See the note above.
            $zoneCode = $hub['zone_code'] ?? $this->slug($hub['name']).'-central';
            $zoneId = $hub['zone_id'] ?? $this->uuid5('zone:'.$zoneCode);
            DB::table('zones')->insertOrIgnore([
                'id' => $zoneId,
                'city_hub_id' => $hubId,
                'kind' => 'zone',
                'code' => $zoneCode,
                'name' => $hub['zone_name'] ?? $hub['name'].' Central',
                'created_at' => $now,
                'updated_at' => $now,
            ]);

            foreach ($hub['areas'] as $areaName) {
                $areaCode = $this->slug($areaName);
                DB::table('areas')->insertOrIgnore([
                    'id' => $this->uuid5('area:'.$hub['code'].':'.$areaCode),
                    'zone_id' => $zoneId,
                    'code' => $areaCode,
                    'name' => $areaName,
                    'created_at' => $now,
                    'updated_at' => $now,
                ]);
            }
        }
    }

    /**
     * @return list<array{name: string, code: string, region: string, hub_id: ?string, zone_id: ?string, zone_code: ?string, zone_name: ?string, areas: list<string>}>
     */
    private function hubs(): array
    {
        return [
${rows}
        ];
    }

    private function slug(string $value): string
    {
        $slug = strtolower($value);
        $slug = preg_replace('/[^a-z0-9]+/', '-', $slug) ?? '';

        return substr(trim($slug, '-'), 0, 60);
    }

    /** RFC 4122 v5 (SHA-1). The same input always yields the same id. */
    private function uuid5(string $name): string
    {
        $namespace = str_replace('-', '', self::NAMESPACE_UUID);
        $bytes = '';
        for ($i = 0; $i < 32; $i += 2) {
            $bytes .= chr((int) hexdec(substr($namespace, $i, 2)));
        }

        $hash = sha1($bytes.$name);

        return sprintf(
            '%08s-%04s-%04x-%04x-%12s',
            substr($hash, 0, 8),
            substr($hash, 8, 4),
            (hexdec(substr($hash, 12, 4)) & 0x0FFF) | 0x5000,
            (hexdec(substr($hash, 16, 4)) & 0x3FFF) | 0x8000,
            substr($hash, 20, 12),
        );
    }
}
`;

writeFileSync(out, php);

const total = hubs.reduce((n, h) => n + h.areas.length, 0);
console.log(`${hubs.length} hubs, ${total} areas -> ${out}`);
for (const h of hubs) {
  console.log(`  ${h.name.padEnd(12)} ${String(h.areas.length).padStart(3)}`);
}
